void __fb_init(int argc, char** argv, char** envp)
{
    u64* auxv;
    u64 window;

    (void)argc;
    (void)argv;
    if (fb_registers != (volatile u64*)0)
        return;

    auxv = (u64*)envp;
    while (*auxv != 0ul)
        auxv = auxv + 1;
    auxv = auxv + 1;

    window = 0ul;
    while (auxv[0] != AT_NULL)
    {
        if (auxv[0] == AT_FRAMEBUFFER)
            window = auxv[1];
        auxv = auxv + 2;
    }
    if (window == 0ul)
        return;

    fb_registers = (volatile u64*)window;
    if (fb_registers[FB_REGISTER_MAGIC] != FB_MAGIC)
    {
        fb_registers = (volatile u64*)0;
        return;
    }
    fb_pixel_base = (u32*)(window + fb_registers[FB_REGISTER_PIXEL_OFFSET]);
    fb_pixel_width = fb_registers[FB_REGISTER_WIDTH];
    fb_pixel_height = fb_registers[FB_REGISTER_HEIGHT];
    fb_row_pixels = fb_registers[FB_REGISTER_STRIDE] / 4ul;
}

int fb_available(void)
{
    return fb_registers != (volatile u64*)0;
}

u64 fb_width(void)
{
    return fb_pixel_width;
}

u64 fb_height(void)
{
    return fb_pixel_height;
}

u64 fb_row_stride(void)
{
    return fb_row_pixels;
}

u32* fb_pixels(void)
{
    return fb_pixel_base;
}

void fb_present(void)
{
    if (fb_registers != (volatile u64*)0)
        fb_registers[FB_REGISTER_PRESENT] = 1ul;
}

/* Eight registers at a time: one store covers the widest group the hardware offers */
static void fb_fill_run(u32* destination, u64 count, u32 color)
{
    while (count != 0ul)
    {
        usize vl = __riscv_vsetvl_e32m8(count);
        __riscv_vse32_v_u32m8((unsigned int*)destination, __riscv_vmv_v_x_u32m8(color, vl), vl);
        destination = destination + vl;
        count = count - (u64)vl;
    }
}

static void fb_copy_run(u32* destination, const u32* source, u64 count)
{
    while (count != 0ul)
    {
        usize vl = __riscv_vsetvl_e32m8(count);
        vuint32m8_t value = __riscv_vle32_v_u32m8((const unsigned int*)source, vl);
        __riscv_vse32_v_u32m8((unsigned int*)destination, value, vl);
        destination = destination + vl;
        source = source + vl;
        count = count - (u64)vl;
    }
}

void fb_clear(u32 color)
{
    if (fb_registers == (volatile u64*)0)
        return;
    fb_fill_run(fb_pixel_base, fb_row_pixels * fb_pixel_height, color);
}

void fb_fill_rect(s64 x, s64 y, s64 width, s64 height, u32 color)
{
    u64 row;
    if (fb_registers == (volatile u64*)0)
        return;
    if (x < 0l)
    {
        width = width + x;
        x = 0l;
    }
    if (y < 0l)
    {
        height = height + y;
        y = 0l;
    }
    if (width <= 0l || height <= 0l)
        return;
    if ((u64)x >= fb_pixel_width || (u64)y >= fb_pixel_height)
        return;
    if ((u64)x + (u64)width > fb_pixel_width)
        width = (s64)(fb_pixel_width - (u64)x);
    if ((u64)y + (u64)height > fb_pixel_height)
        height = (s64)(fb_pixel_height - (u64)y);

    row = 0ul;
    while (row < (u64)height)
    {
        fb_fill_run(fb_pixel_base + ((u64)y + row) * fb_row_pixels + (u64)x, (u64)width, color);
        row = row + 1ul;
    }
}

u64 fb_console_columns(void)
{
    return fb_pixel_width / FB_GLYPH_WIDTH;
}

u64 fb_console_rows(void)
{
    return fb_pixel_height / FB_GLYPH_HEIGHT;
}

void fb_console_reset(u32 foreground, u32 background)
{
    fb_foreground = foreground;
    fb_background = background;
    fb_cursor_column = 0ul;
    fb_cursor_row = 0ul;
    fb_clear(background);
}

static void fb_draw_glyph(u64 column, u64 row, u32 code)
{
    const u8* glyph;
    u32* target;
    u64 line;

    if (code < FB_FIRST_GLYPH || code > FB_LAST_GLYPH)
        code = (u32)'?';
    glyph = fb_font + (u64)(code - FB_FIRST_GLYPH) * (u64)FB_GLYPH_HEIGHT;
    target = fb_pixel_base + row * (u64)FB_GLYPH_HEIGHT * fb_row_pixels + column * (u64)FB_GLYPH_WIDTH;

    line = 0ul;
    while (line < (u64)FB_GLYPH_HEIGHT)
    {
        u32 bits = (u32)glyph[line];
        u64 pixel = 0ul;
        while (pixel < (u64)FB_GLYPH_WIDTH)
        {
            target[pixel] = (bits & (0x80u >> pixel)) != 0u ? fb_foreground : fb_background;
            pixel = pixel + 1ul;
        }
        target = target + fb_row_pixels;
        line = line + 1ul;
    }
}

static void fb_console_scroll(void)
{
    u64 kept = (fb_console_rows() - 1ul) * (u64)FB_GLYPH_HEIGHT * fb_row_pixels;
    u64 shift = (u64)FB_GLYPH_HEIGHT * fb_row_pixels;
    fb_copy_run(fb_pixel_base, fb_pixel_base + shift, kept);
    fb_fill_run(fb_pixel_base + kept, shift, fb_background);
}

static void fb_console_newline(void)
{
    fb_cursor_column = 0ul;
    fb_cursor_row = fb_cursor_row + 1ul;
    if (fb_cursor_row < fb_console_rows())
        return;
    fb_cursor_row = fb_console_rows() - 1ul;
    fb_console_scroll();
}

void fb_console_putc(int character)
{
    if (fb_registers == (volatile u64*)0)
        return;
    if (character == 10)
    {
        fb_console_newline();
        return;
    }
    if (character == 13)
    {
        fb_cursor_column = 0ul;
        return;
    }
    if (character == 9)
    {
        u64 stop = (fb_cursor_column + 8ul) & ~7ul;
        while (fb_cursor_column < stop && fb_cursor_column < fb_console_columns())
        {
            fb_draw_glyph(fb_cursor_column, fb_cursor_row, (u32)' ');
            fb_cursor_column = fb_cursor_column + 1ul;
        }
        if (fb_cursor_column >= fb_console_columns())
            fb_console_newline();
        return;
    }

    if (fb_cursor_column >= fb_console_columns())
        fb_console_newline();
    fb_draw_glyph(fb_cursor_column, fb_cursor_row, (u32)(character & 255));
    fb_cursor_column = fb_cursor_column + 1ul;
}

void fb_console_write(const char* text)
{
    usize index = 0ul;
    while (text[index] != 0)
    {
        fb_console_putc((int)(u8)text[index]);
        index = index + 1ul;
    }
}
